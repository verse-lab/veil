#!/usr/bin/env python3
"""Lines of code of a TLA+ spec and of its Veil translation, and their ratio.

Usage:
    python3 scripts/loc_ratio.py SPEC.tla MODEL.lean
    python3 scripts/loc_ratio.py --dump SPEC.tla MODEL.lean     # also list every counted line
    python3 scripts/loc_ratio.py --pluscal source SPEC.tla MODEL.lean

A line counts when anything other than whitespace and comments is on it.

TLA+
    `\\*` line comments and nested `(* ... *)` block comments are dropped. The module's
    `----` and `====` rules count. A PlusCal algorithm counts from `--algorithm` to its end,
    although it sits in a block comment; comments inside it do not.
    `--pluscal` decides what a PlusCal spec contributes:
      both         the algorithm and the TLA+ generated from it between
                   `\\* BEGIN TRANSLATION` and `\\* END TRANSLATION` (default);
      source       the algorithm, without the generated translation;
      translation  the generated translation, ignoring the algorithm.
    `--before WORD` counts only the lines before the first one that starts with WORD, e.g.
    `--before LEMMA` leaves out TLAPS lemmas and their proofs that follow the spec.

Lean
    `--` line comments and nested `/- ... -/` block comments, including `/-- -/` and `/-! -/`
    doc comments, are dropped. Everything else counts, `#gen_spec` and `#model_check` too.

The ratio is Veil / TLA+, rounded half up to two decimals.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

PLUSCAL_MODES = ("both", "source", "translation")

_PCAL_START = re.compile(r"--(?:fair\s+)?algorithm\b")
#: Group 1 is set for the C syntax, whose body is the brace block after the name.
_PCAL_HEAD = re.compile(r"--(?:fair\s+)?algorithm\s+\w+\s*(\{)?")
_PCAL_END = re.compile(r"end\s+algorithm\b\s*;?")
_TRANSLATION_BEGIN = re.compile(r"\s*\\\*\s*BEGIN TRANSLATION")
_TRANSLATION_END = re.compile(r"\s*\\\*\s*END TRANSLATION")
_LEAN_CHAR = re.compile(r"'(?:\\(?:x[0-9a-fA-F]{2}|u[0-9a-fA-F]{4}|.)|[^\\'\n])'")


@dataclass
class TlaCount:
    lines: list[int]          # counted line numbers (1-based), for the chosen PlusCal mode
    pluscal: int              # lines of PlusCal algorithm code
    translation: int          # code lines generated by the PlusCal translator

    @property
    def loc(self) -> int:
        return len(self.lines)


def _string_end(text: str, i: int) -> int:
    """Index just past the TLA+ string literal opening at `i`. TLA+ strings stay on one line."""
    j, n = i + 1, len(text)
    while j < n and text[j] not in '"\n':
        j += 2 if text[j] == "\\" and j + 1 < n and text[j + 1] != "\n" else 1
    return j + 1 if j < n and text[j] == '"' else j


def _is_ident_char(ch: str) -> bool:
    return ch.isalnum() or ch == "_"


def _tla_scan(text: str) -> tuple[set[int], set[int]]:
    """Lines holding TLA+ code outside comments, and lines holding PlusCal code."""
    tla: set[int] = set()
    pcal: set[int] = set()
    n, i, line = len(text), 0, 1
    depth = 0               # nesting of (* *) comments
    line_comment = False
    in_pcal = False
    pcal_depth = 0          # comment depth at which the algorithm's code sits
    c_syntax = False
    braces = 0
    while i < n:
        ch = text[i]
        if ch == "\n":
            line += 1
            line_comment = False
            i += 1
            continue
        if line_comment:
            i += 1
            continue
        if depth == 0:
            if text.startswith("(*", i):
                depth, i = 1, i + 2
            elif text.startswith("\\*", i):
                line_comment, i = True, i + 2
            elif ch == '"':
                tla.add(line)
                i = _string_end(text, i)
            else:
                if not ch.isspace():
                    tla.add(line)
                i += 1
            continue
        if in_pcal and depth == pcal_depth:
            # Code of the PlusCal algorithm.
            if text.startswith("(*", i):
                depth, i = depth + 1, i + 2
            elif text.startswith("*)", i):
                # The enclosing comment closes, so the algorithm ends here at the latest.
                depth, i, in_pcal = depth - 1, i + 2, False
            elif text.startswith("\\*", i):
                line_comment, i = True, i + 2
            elif ch == '"':
                pcal.add(line)
                i = _string_end(text, i)
            elif not c_syntax and (m := _PCAL_END.match(text, i)) and (
                    i == 0 or not _is_ident_char(text[i - 1])):
                for k in range(i, m.end()):
                    if text[k] == "\n":
                        line += 1
                    elif not text[k].isspace():
                        pcal.add(line)
                i, in_pcal = m.end(), False
            else:
                if not ch.isspace():
                    pcal.add(line)
                if c_syntax and ch == "{":
                    braces += 1
                elif c_syntax and ch == "}":
                    braces -= 1
                    if braces == 0:
                        in_pcal = False
                i += 1
            continue
        # Comment text: prose, or a comment nested inside the algorithm.
        if text.startswith("(*", i):
            depth, i = depth + 1, i + 2
        elif text.startswith("*)", i):
            depth, i = depth - 1, i + 2
        elif not in_pcal and (m := _PCAL_START.match(text, i)):
            head = _PCAL_HEAD.match(text, i)
            in_pcal, pcal_depth = True, depth
            c_syntax, braces = bool(head and head.group(1)), 0
            pcal.add(line)
            i = m.end()
        else:
            i += 1
    return tla, pcal


def _translation_lines(text: str) -> set[int]:
    """Lines strictly between the BEGIN TRANSLATION and END TRANSLATION markers."""
    inside, out = False, set()
    for number, raw in enumerate(text.split("\n"), 1):
        if _TRANSLATION_BEGIN.match(raw):
            inside = True
        elif _TRANSLATION_END.match(raw):
            inside = False
        elif inside:
            out.add(number)
    return out


def count_tla(path: Path, pluscal: str = "both", before: str | None = None) -> TlaCount:
    if pluscal not in PLUSCAL_MODES:
        raise ValueError(f"unknown PlusCal mode {pluscal!r}")
    text = path.read_text(encoding="utf-8")
    if before is not None:
        cut = re.search(rf"^{re.escape(before)}\b", text, re.MULTILINE)
        if cut is None:
            raise ValueError(f"no line of {path} starts with {before}")
        text = text[:cut.start()]
    tla, pcal = _tla_scan(text)
    generated = tla & _translation_lines(text)
    if pluscal == "both":
        lines = tla | pcal
    elif pluscal == "source":
        lines = (tla - generated) | pcal
    else:
        lines = tla
    return TlaCount(sorted(lines), len(pcal), len(generated))


def lean_lines(path: Path) -> list[int]:
    """Line numbers (1-based) of the Lean file that hold code."""
    text = path.read_text(encoding="utf-8")
    code: set[int] = set()
    n, i, line = len(text), 0, 1
    depth = 0               # nesting of /- -/ comments
    line_comment = False
    while i < n:
        ch = text[i]
        if ch == "\n":
            line += 1
            line_comment = False
            i += 1
        elif line_comment:
            i += 1
        elif depth > 0:
            if text.startswith("/-", i):
                depth, i = depth + 1, i + 2
            elif text.startswith("-/", i):
                depth, i = depth - 1, i + 2
            else:
                i += 1
        elif text.startswith("/-", i):
            depth, i = 1, i + 2
        elif text.startswith("--", i):
            line_comment, i = True, i + 2
        elif ch == '"':
            # String literals may span lines.
            code.add(line)
            i += 1
            while i < n and text[i] != '"':
                if text[i] == "\\" and i + 1 < n:
                    if text[i + 1] == "\n":
                        line += 1
                    i += 2
                    continue
                if text[i] == "\n":
                    line += 1
                elif not text[i].isspace():
                    code.add(line)
                i += 1
            i += 1
        elif ch == "'" and (i == 0 or not (_is_ident_char(text[i - 1]) or text[i - 1] in "'!?.")) \
                and (m := _LEAN_CHAR.match(text, i)):
            # A character literal such as '"' must not open a string.
            code.add(line)
            i = m.end()
        else:
            if not ch.isspace():
                code.add(line)
            i += 1
    return sorted(code)


def count_lean(path: Path) -> int:
    return len(lean_lines(path))


def ratio(tla_loc: int, veil_loc: int) -> str:
    """Veil / TLA+ with two decimals, rounded half up."""
    if tla_loc <= 0:
        return "--"
    return str((Decimal(veil_loc) / Decimal(tla_loc)).quantize(Decimal("0.01"), ROUND_HALF_UP))


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Count the lines of code of a TLA+ spec and its Veil translation, "
                    "and print their ratio (Veil / TLA+).")
    parser.add_argument("tla", type=Path, help="the TLA+ module (.tla)")
    parser.add_argument("veil", type=Path, help="the Veil model (.lean)")
    parser.add_argument("--pluscal", choices=PLUSCAL_MODES, default="both",
                        help="what a PlusCal spec contributes (default: both; see the module doc)")
    parser.add_argument("--before", metavar="WORD",
                        help="count the TLA+ module only before the first line that starts with WORD")
    parser.add_argument("--dump", action="store_true", help="also print every counted line")
    parser.add_argument("--json", action="store_true", help="print the result as JSON")
    args = parser.parse_args()

    try:
        tla = count_tla(args.tla, args.pluscal, args.before)
    except ValueError as error:
        parser.error(str(error))
    veil = lean_lines(args.veil)
    result = {"tla": str(args.tla), "veil": str(args.veil), "pluscal_mode": args.pluscal,
              "tla_before": args.before,
              "tla_loc": tla.loc, "veil_loc": len(veil), "ratio": ratio(tla.loc, len(veil)),
              "tla_pluscal_lines": tla.pluscal, "tla_translation_lines": tla.translation}
    if args.json:
        print(json.dumps(result, indent=2))
    else:
        print(f"TLA+   {tla.loc:5d}  {args.tla}")
        if args.before:
            print(f"       (only the lines before the first one that starts with {args.before})")
        if tla.pluscal:
            print(f"       (PlusCal {tla.pluscal}, generated translation {tla.translation};"
                  f" --pluscal {args.pluscal})")
        print(f"Veil   {len(veil):5d}  {args.veil}")
        print(f"Ratio  {result['ratio']:>5}  (Veil / TLA+)")
    if args.dump:
        for path, numbers in ((args.tla, tla.lines), (args.veil, veil)):
            raw = path.read_text(encoding="utf-8").split("\n")
            print(f"\n== counted lines of {path}", file=sys.stderr)
            for k in numbers:
                print(f"{k:5d}  {raw[k - 1]}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
